def apply_canonical(corpus):
    """Apply PATCH overrides to corpus poem bodies."""
    for poet_id, poems in corpus.items():
        for poem in poems:
            key = (poet_id, poem["title"])
            if key in PATCH:
                poem["body"] = PATCH[key].strip()
